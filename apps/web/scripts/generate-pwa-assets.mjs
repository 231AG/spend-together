// F12-02: the install icons and the manifest's colours, generated from the design tokens
// so nothing is typed in by hand. Run after a token or brand change:
//
//   node scripts/generate-pwa-assets.mjs
//
// Writes public/icons/*.png (rendered by the pre-installed Chromium) and
// lib/pwa-colors.generated.ts. lib/pwa-colors.test.ts fails if the two drift apart.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { chromium } from '@playwright/test';

const here = import.meta.dirname;
const web = path.resolve(here, '..');
const css = readFileSync(
  path.resolve(web, '..', '..', 'packages', 'config', 'tailwind', 'tokens.css'),
  'utf8',
);
const root = /:root\s*\{([\s\S]*?)\n\}/.exec(css)?.[1] ?? '';
const tokens = new Map(
  [...root.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]),
);

/** Resolve a token through var() aliases to its literal value. */
function token(name) {
  const value = tokens.get(name);
  if (value === undefined) throw new Error(`No token --${name}`);
  const alias = /^var\(--([\w-]+)\)$/.exec(value);
  return alias ? token(alias[1]) : value;
}

const colors = {
  /** The brand tile and the browser/OS chrome around the installed app. */
  theme: token('action-primary-bg'),
  /** The splash and window background before the app paints. */
  background: token('bg-app'),
  /** The letters on the tile. */
  mark: token('action-primary-fg'),
};

writeFileSync(
  path.join(web, 'lib', 'pwa-colors.generated.ts'),
  `// Generated by scripts/generate-pwa-assets.mjs from packages/config/tailwind/tokens.css.
// Do not edit: change the tokens and run the script again.
export const PWA_COLORS = ${JSON.stringify(colors, null, 2)
    .replace(/"(\w+)":/g, '$1:')
    .replace(/"/g, "'")} as const;
`,
);

/** The "ST" brand tile. Maskable icons keep the mark inside the central 80% safe zone. */
function page(size, maskable) {
  const mark = Math.round(size * (maskable ? 0.34 : 0.42));
  const radius = maskable ? 0 : Math.round(size * 0.22);
  return `<!doctype html><html><body style="margin:0">
<div style="width:${size}px;height:${size}px;display:grid;place-items:center;background:${colors.theme};border-radius:${radius}px;
font:700 ${mark}px/1 system-ui,-apple-system,'Segoe UI',Roboto,sans-serif;letter-spacing:-0.02em;color:${colors.mark}">ST</div>
</body></html>`;
}

const outputs = [
  ['icon-192.png', 192, false],
  ['icon-512.png', 512, false],
  ['maskable-512.png', 512, true],
  ['apple-touch-icon.png', 180, true],
];

const out = path.join(web, 'public', 'icons');
mkdirSync(out, { recursive: true });
// Locally, the pre-installed Chromium; in CI, Playwright's own download.
const executablePath = process.env.CI ? undefined : '/opt/pw-browsers/chromium';
const browser = await chromium.launch(executablePath ? { executablePath } : {});
const tab = await browser.newPage();
for (const [name, size, maskable] of outputs) {
  await tab.setViewportSize({ width: size, height: size });
  await tab.setContent(page(size, maskable));
  await tab.screenshot({ path: path.join(out, name), omitBackground: !maskable });
}
await browser.close();
console.log(`Wrote ${outputs.length} icons and lib/pwa-colors.generated.ts`);
